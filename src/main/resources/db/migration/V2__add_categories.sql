CREATE TABLE categories
(
    id   bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL UNIQUE CHECK (name ~ '[^[:space:]]')
);

INSERT INTO categories (name)
SELECT DISTINCT category
FROM expenses;

