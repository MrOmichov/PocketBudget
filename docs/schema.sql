-- Do not run this alongside migrations. For startup use an empty database.
-- Seeds and flyway_schema_history are not included.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    CHECK (username ~ '^[a-z0-9_]{3,50}$')
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount bigint NOT NULL CHECK (amount > 0),
    spent_at date NOT NULL,
    category_id bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT expenses_category_fk FOREIGN KEY (category_id)
        REFERENCES categories(id) ON DELETE RESTRICT,
    CONSTRAINT expenses_user_fk FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE RESTRICT
);

CREATE INDEX expenses_user_date_id_idx
    ON expenses(user_id, spent_at DESC, id DESC);
